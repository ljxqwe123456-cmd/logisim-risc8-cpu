; 16 位减法（多字节，SUB/SBC）: 0x0200 - 0x0001 = 0x01FF
; 验证时机：§8 第 8 步。**无 k=3、无 load-use、无分支**——四条 LDI 的排布刻意让每个
;           读 Rd 的那条的 RAW 距离落在 k=1 / k=2 / k>=4（见每条的标注），所以只需两个前递 mux
;           就能跑对，不依赖 §4.1 的下降沿写口。拿它验借位时不会混进冒险问题。
;   A = 0x0200 → Ahi=R1(0x02), Alo=R2(0x00)
;   B = 0x0001 → Bhi=R3(0x00), Blo=R4(0x01)
; SUB 低字节（产生借位，C 变 0 = 有借位），SBC 高字节（减借位）。
; 结果: R6:R5 = 0x01FF（OUT 低字节 0xFF、高字节 0x01）

        LDI R1, 0x02     ; A 高字节
        LDI R3, 0x00     ; B 高字节   <- 排在这里（而非紧跟 R2）是为了把它推离 SBC 到 k=4
        LDI R2, 0x00     ; A 低字节
        LDI R4, 0x01     ; B 低字节

        SUB R5, R2, R4   ; 低: 0x00 - 0x01 = 0xFF, 借位=1（C=0）   R2 距 02 k=2，R4 距 03 k=1
        SBC R6, R1, R3   ; 高: 0x02 - 0x00 - 借位 = 0x01             R1 距 00 k=5，R3 距 01 k=4

        OUT R5           ; 低字节 0xFF
        OUT R6           ; 高字节 0x01  → 结果 0x01FF
        HLT
