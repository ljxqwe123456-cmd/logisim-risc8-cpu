; 子程序调用约定（R15 = 栈指针，R14 = 链接寄存器）的集成判据：OUT = 0x0C。
; 验证时机：§8 第 7 步（JMP Rs 与它的 flush 都接上之后）。
;
; 调用约定（本 ISA 没有 CALL / RET，全部用现有指令拼出来）：
;   调用方：LDI R14, 返回标签        —— 返回地址进链接寄存器
;           JMP   子程序入口         —— 用绝对地址跳进去
;   子程序：ST  R14, [R15]           —— 先把自己要用的 R14 压栈
;           ADD R15, R15, #1         —— 栈指针后加（栈往上长）
;           ...                      —— 可以再调用别的子程序（R14 已被保住）
;           ADD R15, R15, #0xFF      —— 栈指针先减
;           LD  R14, [R15]           —— 弹栈
;           JMP R14                  —— 返回
;   R14 只有一份，所以子程序只要自己还会调用别人，就必须先压栈——本程序 outer 连调两次 dbl，
;   就是这一条的最小复现。R15 初值取哪个地址由调用方定，本程序取 0x60；RAM 上电值不定，
;   程序只读自己写过的格子（0x60），所以不用先清零。
;
; 判据怎么读：
;   0x0C = 正解。R1 从 3 被 dbl 翻两次：3 → 6 → 12，07 把它显示出来。
;   0x03 = taken 那一项漏接。04 后面的 05、06 是两条 MOV R7,R7（不改任何状态）：
;          ID/EX 清零漏了只多跑 05，IF/ID 灌 0 漏了只多跑 06，两处都漏就两条都跑；
;          三种情况都接着走到 07、把还没翻倍的 R1 显示出来。
;   无输出（显示屏不动）= 下面两项之一没接：11 的 JMP R14 拿到 0，PC 回 0 原地打转，
;          07 的 OUT 再也走不到。
;            §4 前递优先级 1：0F 写 R15 → 10 读 R15 是 k=1，断掉时 10 拿到的 R15 是 0x61，
;              读到的是没写过的 RAM[0x61]，值为 0。
;            §5.2 load-use：10 是 load → 11 是 JMP R14，同一条停顿规则；不停顿时 11
;              拿到的 R14 是旧的 0x0F，跑到 0F 之后同样以 0 返回。
;
; 刻意不考 k=3 与 §4 前递优先级 2：全文的 RAW 间隔都是 1（上面两项）、4 或更远，
; 没有正好相隔 3 条的；03 那条填充把 01 的 R14 推到 k=4，13 那条把返回地址的 k=3 推到 k=4。
; 这两项分别由 hazard_k3.asm 与 hazard_k2branch.asm 判。
;
; 寄存器：R1 = 被翻倍的值，R14 = 链接寄存器，R15 = 栈指针，R7 = 填充用的恒等拷贝

        LDI R15, 0x60    ; SP
        LDI R14, r1      ; 返回地址
        LDI R1, 3        ; dbl 翻倍两次后是 12
        LDI R7, 0        ; 填充：把 01 的 R14 与 09 的 ST 拉开到 k=4
        JMP outer
        MOV R7, R7       ; 白取填充①（ID/EX 漏清才执行）
        MOV R7, R7       ; 白取填充②（IF/ID 漏灌 0 才执行）
r1:     OUT R1           ; 正解 0x0C
        HLT
outer:  ST  R14, [R15]   ; 压栈：outer 自己还要调用 dbl，先保住调用方的返回地址
        ADD R15, R15, #1 ; SP++
        LDI R14, o1      ; dbl 第一次返回后落在 o1
        JMP dbl
o1:     LDI R14, o2      ; dbl 第二次返回后落在 o2
        JMP dbl
o2:     ADD R15, R15, #0xFF ; SP--
        LD  R14, [R15]   ; 弹栈：取回调用方的返回地址
        JMP R14          ; 返回
dbl:    ADD R1, R1, R1   ; 翻倍
        MOV R7, R7       ; 填充：把 0B / 0D 的 LDI R14 与 14 的 JMP R14 都拉到 k=4
        JMP R14          ; 返回
