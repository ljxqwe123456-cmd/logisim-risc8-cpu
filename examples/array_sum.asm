; 数组累加（寄存器间接寻址 + 指针）：求 [5,7,9] 之和，OUT = 21 (0x15)
; 验证时机：§8 第 7 步。含 k=3 RAW（08 读 R1，见 §4.1）、load-use（0E 紧接 0D 的 LD）、
;           taken 分支（11 的 BNZ 读紧邻的 10 产生的 R3，每轮都跳）。
;
; 它有效的判据是三处，各有一个不同的失败值：
;   k=3 那处（08 读 R1，写它的是 05）：指针少进一格，0A 的 ST 把 7 覆盖掉、第三个格子没人写
;     → 读回 5+9+0 = **0x0E**；
;   前递优先级 1（三条 ST 的数据源 R5 都紧接在 LDI 之后，k=1）：接漏了写进 RAM 的全是 0
;     → **0x00**；
;   前递优先级 2（0D 的 LD 读 0B 写的 R1，k=2）：接漏了它读回的 R1 是旧的 0x12，
;     于是三轮累加的是 9、7、9，**0x19**。
;
; load-use 与 taken 作废那两处则是假通过——
;   0E 漏停顿：累加的是 {9,5,7} 而非 {5,7,9}，但**两组和都是 21**；
;   11 的前递接错：BNZ 读到旧的 R3（比正确的值大 1），多跑一轮，多读的 RAM[0x13] 是 0，
;     **sum += 0，输出仍是 21**；
;   11 漏清 ID/EX：顺落的 12 的 OUT R2 每轮多执行一次，但最后那次仍是正解的 21。
; 要验 load-use 用 square_lookup.asm，要验 taken 作废用 hazard_flush.asm。详见 README.md 的判据表。
; 流程:
;   1) 用 ST Rs,[指针] 把 5,7,9 依次写入 RAM 0x10..0x12
;   2) 指针复位到 0x10，用 LD Rd,[指针] 读出累加
; 寄存器约定:
;   R1 = 指针（数组地址）
;   R2 = 累加和
;   R3 = 剩余元素个数（倒计数）
;   R4 = 常数 1（指针步进 / 计数递减）
;   R5 = 临时（写/读元素值）

        LDI R1, 0x10     ; 指针 = 数组基址
        LDI R4, 1        ; 常数 1
        LDI R3, 3        ; 元素个数

        ; --- 写数组 ---
        LDI R5, 5
        ST  R5, [R1]     ; RAM[0x10] = 5
        ADD R1, R1, R4   ; 指针++
        LDI R5, 7
        ST  R5, [R1]     ; RAM[0x11] = 7
        ADD R1, R1, R4
        LDI R5, 9
        ST  R5, [R1]     ; RAM[0x12] = 9

        ; --- 读数组累加 ---
        LDI R1, 0x10     ; 指针复位
        LDI R2, 0        ; sum = 0

sumloop:
        LD  R5, [R1]     ; R5 = *ptr
        ADD R2, R2, R5   ; sum += *ptr
        ADD R1, R1, R4   ; ptr++
        SUB R3, R3, R4   ; count--
        BNZ R3, sumloop

        OUT R2           ; 5+7+9 = 21
        HLT
