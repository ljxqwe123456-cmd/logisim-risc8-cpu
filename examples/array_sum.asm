; 数组累加（寄存器间接寻址 + 指针）：求 [5,7,9] 之和，OUT = 21 (0x15)
; 验证时机：§8 第 7 步。含 k=3 RAW（08 读 R1，见 §4.1）、load-use（0E 紧接 0D 的 LD）、
;           §5 分支冒险（11 的 BNZ 读紧邻的 10 产生的 R3）。
;
; **它只有 k=3 与 `&& !stall` 两项有效**，分支那两条是假通过——
;   0E 漏停顿：累加的是 {9,5,7} 而非 {5,7,9}，但**两组和都是 21**；
;   11 漏停顿：多跑一轮，多读的 RAM[0x13] 是 0，**sum += 0，输出仍是 21**；
;   而去掉 §5.1 的 `&& !stall` 则相反：11 的 BNZ 被自己 flush 掉，循环只跑一轮、输出 0x05。
;   去掉 §4.1 的下降沿写口（k=3 那处）：指针少进一格，第二次 ST 把 7 覆盖掉、第三个格子没人写
;   → 读回 5+9+0 = **0x0E**（不是 0x00，也不同于上面那些"仍是 21"的假通过）。
; 要验 load-use 用 square_lookup.asm，要验分支用 hazard_branch.asm。详见 README.md 的判据表。
; 流程:
;   1) 用 ST Rs,[指针] 把 5,7,9 依次写入 RAM 0x10..0x12
;   2) 指针复位到 0x10，用 LD Rd,[指针] 读出累加
; 寄存器约定:
;   R1 = 指针（数组地址）
;   R2 = 累加和
;   R3 = 剩余元素个数（倒计数）
;   R4 = 常数 1（指针步进 / 计数递减）
;   R5 = 临时（写/读元素值）

        LDI R1, 0x10     ; 指针 = 数组基址
        LDI R4, 1        ; 常数 1
        LDI R3, 3        ; 元素个数

        ; --- 写数组 ---
        LDI R5, 5
        ST  R5, [R1]     ; RAM[0x10] = 5
        ADD R1, R1, R4   ; 指针++
        LDI R5, 7
        ST  R5, [R1]     ; RAM[0x11] = 7
        ADD R1, R1, R4
        LDI R5, 9
        ST  R5, [R1]     ; RAM[0x12] = 9

        ; --- 读数组累加 ---
        LDI R1, 0x10     ; 指针复位
        LDI R2, 0        ; sum = 0

sumloop:
        LD  R5, [R1]     ; R5 = *ptr
        ADD R2, R2, R5   ; sum += *ptr
        ADD R1, R1, R4   ; ptr++
        SUB R3, R3, R4   ; count--
        BNZ R3, sumloop

        OUT R2           ; 5+7+9 = 21
        HLT
