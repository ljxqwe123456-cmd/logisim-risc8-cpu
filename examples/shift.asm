; 五条移位里的三条（SLL / SRL / SRA，fn 9-11）的独立判据：OUT = 0x96。
; 验证时机：§8 第 2 步（接 ALU 时先拿常量按 docs/datapath.md §2.2 的表验五码）；
;           这条程序只用到 ALU 与 OUT，第 4 步就能跑（那时各级直连、没有冒险）。
; 另两条（SLC / SRC）的判据在 shift_carry.asm。
;
; 判据怎么读，五个值各不相同：
;   0x96 = 正解。
;   0x17 = SRA 的填位接成了 0（当成逻辑右移）。两处 SRA 各少一位符号：#1 给出 0x52
;          （应为 0xD2）、#8 给出 0x00（应为 0xFF）。SLL / SRL 不受影响。
;   0xDE = 移位器整条没接上。译码器漏了 fn 9-11 时 ALUop 那三级 mux 落回 PASS.A，
;          六次移位全都原样搬回 0xA5。
;   0xE1 = ≥8 的检测没接。移位控制直接吃 B[2:0]，#8 被当成移 0 位，结果还是 0xA5。
;   0x62 = 移位控制接在 BSrc 之前。立即数型的移位量拿不到（那五条的 rs2 槽是 0），
;          只有 SRL R6,R1,R2 那一条拿的是真移位量、算对了。
;
; 被移的数取 0xA5（10100101），是为了让三个方向各给出一个不同的字节（0x4A / 0x52 / 0xD2）；
; 它的高两位一 0 一 1，又让 #8 那两条的"整字节移空"与"全符号位"分得开。
;
; 刻意不考 k=3、load-use 与 taken 作废：
;   被移的数在 00 写、04 起才读，最近的一次是 k=4，走寄存器堆；六次移位各写自己的目标，
;   下一个读它的是 10 起的折叠链，相隔 5 条以上，也走寄存器堆；
;   全文没有 LD、没有分支，load-use 与 taken 作废都碰不到。
;   折叠链上的 R7 每次相隔 1 条，依赖前递优先级 1——那条不通时也会算出别的值，不在上表里。
;
; 寄存器：R1 = 被移的数，R2 = 走寄存器的那个移位量，R3-R6 / R8 / R9 = 六次移位的结果，
;         R7 = 折叠和，R10 = 填充用

        LDI R1, 0xA5     ; 被移的数
        LDI R2, 2        ; 走寄存器的那份移位量
        MOV R10, R10     ; 填充两拍：让 04 起读 R1 都落在 k>=4
        MOV R10, R10
        SLL R3, R1, #1   ; 0xA5 << 1  = 0x4A
        SRL R4, R1, #1   ; 0xA5 >> 1  = 0x52
        SRA R5, R1, #1   ; 0xA5 >>> 1 = 0xD2（算术：高位补符号位）
        SRL R6, R1, R2   ; 0xA5 >> 2  = 0x29（移位量从 Rs2 来）
        SLL R8, R1, #8   ; ≥8：整字节移空    = 0x00
        SRA R9, R1, #8   ; ≥8 且带符号       = 0xFF
        ADD R7, R3, R4   ; 折叠：0x4A + 0x52 = 0x9C
        ADD R7, R7, R5   ; + 0xD2 = 0x6E
        ADD R7, R7, R6   ; + 0x29 = 0x97
        ADD R7, R7, R8   ; + 0x00 = 0x97
        ADD R7, R7, R9   ; + 0xFF = 0x96
        OUT R7
        HLT
