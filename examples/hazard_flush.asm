; 冒险自测 5：taken 时要作废两条顺落指令（见 docs/datapath.md §5.1）
; 验证时机：§8 第 7 步（分支判定 + flush + PC 控制）。
;           无 k=3、无 load-use、无停顿 —— 本条只考"作废"这一件事。
;
; 分支判定在 EX 段做，比 ID 段晚一拍，所以 taken 时已经在飞的有两条顺落指令，
;   两处都要清：
;     - IF/ID 灌全 0（保留码 op=0000）：丢掉还在 IF 段的那条；
;     - ID/EX 的 D 端清零：丢掉正在 ID 译码、下一拍本要进 EX 的那条。
;   只做前者，白取的那条会晚一拍照样执行完。
;
; 两条通路各带一条白取指令当探针：05 的条件分支后面跟着 06，08 的 JMP 后面跟着 09。
;   它们若被执行，就把 0x11 / 0x22 写进 R3，最后由 11 的 OUT R3 显示出来。
;
; 期望：OUT 显示 0x00（R3 在 00 行清 0，之后一行都不该被执行到）。
; 若显示 0x11：05 那一路漏清（ID/EX 清零的选择端漏了 branch_taken），
;   或者 IF/ID 根本没灌全 0。
; 若显示 0x22：08 那一路漏清（选择端漏了 ID_EX.Jump）。两条都漏时先执行的 0x11
;   被后执行的 0x22 覆盖，显示的仍是 0x22 —— 看到 0x22 时两路都要查。
;
; 02-04 三行填充不能省：BNZ 的源 R2 由 01 写，三条填充把它推到 k=4、走寄存器堆。
;   少了填充，前递一旦接错，BNZ 读到旧的 R2=0 就【不】跳，顺落的 06 执行、
;   同样显示 0x11，与"漏清 ID/EX"的症状一字不差。

        LDI R3, 0        ; 判据寄存器：清 0
        LDI R2, 1        ; BNZ 的源，i=1
        LDI R5, 0        ; 填充 ×3：把 R2 与 05 的距离推到 k=4，避开前递
        LDI R6, 0
        LDI R7, 0
        BNZ R2, tgt      ; R2 = 1 ≠ 0 → 跳（taken），作废 06 与 07
        LDI R3, 0x11     ; <- 条件分支的白取指令
        HLT
tgt:    JMP over         ; 无条件跳转，作废 09 与 10
        LDI R3, 0x22     ; <- JMP 的白取指令
        HLT
over:   OUT R3           ; 0x00 <- 正解走这里
        HLT
