; 冒险自测 1：间隔正好 3 条的 RAW 依赖（见 docs/datapath.md §4.1）
; 验证时机：§8 第 1 / 6 / 7 步——下降沿写口（第 1 步）+ 前递 mux（第 6 步）+ Hazard Unit（第 7 步）三件套齐了才对。
;           （07 的 OUT 紧跟 06 的 LDA，另有 load-use，属第 7 步。）
;
; 05 的 ST 用 R1 做地址，而 R1 由 02 写入 —— 两者相隔正好 3 条指令。
;   k=1 / k=2 由 EX 段的前递 mux 覆盖，k>=4 寄存器堆里早已是新值，
;   只有 k=3 两头都够不着：读 Rd 的那条在 ID 读寄存器堆时写 Rd 的那条还没写回，
;   等读 Rd 的那条进 EX 时写 Rd 的那条又已经流出流水线。
; 正解：寄存器堆的写口用下降沿（同拍内 WB 的写先于 ID 的读生效）。
;
; 期望：OUT 显示 0xFF。
; 若显示 0x00：05 读到的 R1 是旧值 0，ST 写进了 RAM[0]，
;             RAM[0x10] 从没被动过，LDA 读回预置的 0。

        LDI R5, 0
        STA R5, 0x10     ; 先把 RAM[0x10] 清 0，让判据不受 RAM 初值影响
        LDI R1, 0x10     ; 基址 —— 写 Rd 的那条
        LDI R3, 0        ; 填充，把 ST 与 LDI R1 拉开到正好 k=3
        LDI R2, 0xFF     ; 待写入的值（紧邻 ST，k=1，走 B 前递 → 写数据）
        ST  R2, [R1]     ; <- 用 R1，相隔 k=3
        LDA R4, 0x10     ; 用绝对地址读回，不依赖 R1
        OUT R4           ; 0xFF
        HLT
