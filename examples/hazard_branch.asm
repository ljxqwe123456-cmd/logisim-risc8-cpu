; 冒险自测 2：分支的源由紧邻的前一条产生（k=1，见 docs/datapath.md §5.2 ②）
; 验证时机：§8 第 7 步（分支判零 + ID 前递 + Hazard Unit + flush）。
;           无 load-use，静态上也无 k=3 —— 但**它三项全考**，见文末"注意"。
;
; 03 的 BZ 在 ID 段判零，要的是 R3 已经算出来的值，而 R3 由紧邻的 02 产生（k=1）。
;   03 在 ID 的那一拍，02 正在 EX —— 它的结果此刻还不存在；
;   EX/MEM 装的是再前一条、MEM/WB 装的是更前一条，两个 ID 前递源都够不着。
; 正解：本条要【先停顿 1 拍】，让 02 走到 EX/MEM，再由 EX/MEM→ID 前递拿到 R3。
;   两处都要对，缺一不可：
;     ① 停顿条件不能带 ID_EX.MemRead —— 读 Rd 的那条是 BZ/BNZ 时要挡全部类型，
;        不能只挡 load（原 load-use 规则只盖住了"前一条是 load"这一种）；
;     ② 分支操作数的 3 选 1 mux 必须接 EX/MEM 这一路（§5.1），只接 MEM/WB 够不着。
;
; 期望：OUT 显示 5（R3 = 5 ≠ 0 → 不跳，落到 04 的 OUT R3）。
; 若显示 0x10：BZ 读到了旧的 R3（= 0）而误判跳转，跑进了 wrong 分支。
;
; 注意：本条**三项修复全考**，不要以为它只测分支：
;   1) ② 停顿：把 branch_stall 关掉 → OUT = 0x10；
;   2) §5.1 的 EX/MEM 那一路 ID 前递：只留 MEM/WB → OUT = 0x10；
;   3) §4.1 的寄存器堆下降沿写口：改回上升沿 → OUT = 0x00。
;   第 3 项的原因很隐蔽：**为 03 插入的那 1 拍停顿，把后面 04 的 `OUT R3` 从静态的
;   k=2 推成了流水线意义上的 k=3**（MOV R3 在 WB 的那一拍，OUT R3 正好在 ID 读口）。
;   所以"静态看没有 k=3"不等于"运行时不会遇到 k=3"——插停顿会改变后面读 Rd 的那条的有效距离。
;
; 另：本条对 §5.1 的 `&& !stall` 是**假通过**——去掉它，03 的 BZ 在停顿拍上读到旧 R3=0、
;     判"该跳"、确实把 BZ 自己 flush 掉了，但顺落的 04 `OUT R3` 恰好就是"不跳"该走的
;     正解路径，输出仍是 5（旧值 0 与新值 5 判出的"跳/不跳"不同，可见条件没满足）。
;     要验那一项用 fib.asm。
;
; 另：本条的 k=2（不停顿、纯靠 EX/MEM 前递）分支见 hazard_k2branch.asm；
;     分支的源来自一条在飞的 load 见 hazard_loadbranch.asm。

        LDI R1, 0x10
        LDI R2, 5
        MOV R3, R2       ; R3 = 5（紧邻 BZ，k=1）
        BZ  R3, wrong    ; R3 ≠ 0，应【不】跳
        OUT R3           ; 5    <- 正解走这里（先停 1 拍，再由 EX/MEM→ID 前递）
        HLT
wrong:  OUT R1           ; 0x10 <- 误跳走这里
        HLT
