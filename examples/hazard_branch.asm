; 冒险自测 2：分支的操作数由紧邻的前一条产生（k=1，见 docs/datapath.md §5.1）
; 验证时机：§8 第 7 步（分支判定 + flush + PC 控制）。
;           无停顿、无 taken 分支、无 k=3 —— 本条考 A 前递 mux 的优先级 1（03 的 BZ）
;           与优先级 2（04 的 OUT R3，见下）。
;
; 03 的 BZ 在 EX 段判零，要的是 R3 已经算出来的值，而 R3 由紧邻的 02 产生（k=1）。
;   03 走到 EX 那一拍，02 正好在 EX/MEM —— A 前递 mux 的优先级 1 够得着它。
; 正解：不需要任何停顿，优先级 1 当拍把 R3 = 5 换进 ALU 的 A 侧。
;
; 期望：OUT 显示 5（R3 = 5 ≠ 0 → 不跳，落到 04 的 OUT R3）。
; 若显示 0x10：优先级 1 没接。这一刻 MEM/WB 里装的是 01 的 LDI R2（rd=2≠3），
;   只靠优先级 2 取不到 R3，BZ 读到旧的 R3（= 0）而误判跳转，跑进了 wrong 分支。
;
; 04 的 OUT R3 读的也是 02 写的 R3，距离 k=2 —— 那处落在优先级 2 上：少了它，OUT 拿不到
;   前递来的 R3，读回寄存器堆里的旧值 0，显示 0x00（本条的第二种失败值，与 5 / 0x10 都不同）。
;
; 三处 RAW 的距离分别是 k=1、k=2、k≥4（wrong 里的 OUT R1 读 R1），都不是 k=3 ——
;   所以寄存器堆写口改回上升沿，本条照样显示 5。k=3 用 hazard_k3.asm。
;
; 另：优先级 2 的单独判据是 hazard_k2branch.asm（本条两处 RAW 叠在一起，分不出是哪个 mux 坏）；
;     源来自一条在飞的 load 见 hazard_loadbranch.asm；taken 时要作废两条顺落指令见 hazard_flush.asm。

        LDI R1, 0x10
        LDI R2, 5
        MOV R3, R2       ; R3 = 5（紧邻 BZ，k=1）
        BZ  R3, wrong    ; R3 ≠ 0，应【不】跳
        OUT R3           ; 5    <- 正解走这里（优先级 1 当拍前递）
        HLT
wrong:  OUT R1           ; 0x10 <- 误跳走这里
        HLT
