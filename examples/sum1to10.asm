; 计数循环: 求 1+2+...+10，结果 OUT = 55 (0x37)
; 验证时机：§8 第 7 步。这是带 taken 分支的循环的实际使用场景，也是 k=3 的判据之一。
;
; 两处 k=3 RAW（见 §4.1）：
;   04 的 SUB R2,R2,R3 读的 R2 由 01 的 LDI R2,10 写，中间没有气泡，是实打实的 k=3；
;   03 的 ADD R1,R1,R2 读的 R1 同样相隔 k=3，但它的旧值恰好也是 0（00 行就是 LDI R1,0），
;   写口坏掉时读不出差别 —— 起判据作用的是 04 那条。
;   去掉下降沿写口 → 输出 0x8A 而不是 0x37：首轮 04 读到旧的 R2=0，0-1 回绕成 255，
;   循环从那里一路倒计数、共跑 256 轮（R1 = 10 + 255+…+1 = 32650，取低 8 位）。
;
; 注意循环体里 03 的 ADD 与上一轮的它自己静态相隔 3 条，但每轮末尾那次 taken 的 BNZ
;   要作废 2 条（§5.1），实际是 k=5、走寄存器堆，不算 k=3 —— k 是运行时距离，
;   不是源码里数出来的条数（§4.2）。
;
; 本条有效的判据是 k=3 与前递优先级 2 两项：
;   后者接漏时 04 的 SUB 读到的 R3 是旧值 0，R2 永远减不掉、循环根本停不下来（没有输出）。
; 分支那几处它验不出来：05 的 BNZ 即使读到多一轮的旧值也只会让循环多跑一轮，而那一轮
;   n 已是 0、sum 加的是 0，输出仍是 55；taken 时漏作废两条也只是让顺落的 06 多执行几次，
;   最后那次仍是 55。要验那几处，用 hazard_branch / hazard_k2branch / hazard_flush。
;   详见 README.md 的判据表。
; 寄存器约定:
;   R1 = 累加和
;   R2 = 当前计数值（倒计数 10 → 0）
;   R3 = 常数 1

        LDI R1, 0        ; sum = 0
        LDI R2, 10       ; n = 10
        LDI R3, 1        ; 常数 1

loop:
        ADD R1, R1, R2   ; sum += n
        SUB R2, R2, R3   ; n--
        BNZ R2, loop     ; n != 0 继续

        OUT R1           ; 55
        HLT
