; 计数循环: 求 1+2+...+10，结果 OUT = 55 (0x37)
; 验证时机：§8 第 7 步。含 k=3 RAW ×2（03 读 R1、04 读 R2，见 §4.1）
;           + §5 分支冒险（05 的 BNZ 读紧邻的 04 产生的 R2）。
;           两处 k=3 里只有 04 那条验得出东西——03 那条的旧值恰好也是 0（00 行就是 LDI R1,0）。
;           去掉下降沿写口 → 输出 **0x8A** 而不是 0x00：首轮 04 读到旧的 R2=0，0−1 回绕成 255，
;           循环从那里一路倒计数、共跑 256 轮（R1 = 10 + 255+…+1 = 32650，取低 8 位）。
;           注意 06 的 OUT R1 与 03 静态相隔 3 条，但被 05 那拍停顿推成了 k=4、不算 k=3
;           ——插停顿会改变后面读 Rd 的那条的有效距离（CLAUDE.md 易错点 8）。
;
; **它是 k=3 与 `&& !stall` 两项的有效判据**，分支那两项验不了：
;   去掉 §5.2 ② 的分支停顿或 §5.1 的 EX/MEM→ID 前递 → 输出仍是 55（多跑一轮，但那一轮 n 已是 0，sum += 0）；
;   去掉 §5.1 的 `&& !stall` → 05 的 BNZ 在停顿拍上被自己 flush 掉，循环只跑一轮、输出 0x0A。
; 详见 README.md 的判据表。要验分支那两项，用 hazard_branch.asm。
; 寄存器约定:
;   R1 = 累加和
;   R2 = 当前计数值（倒计数 10 → 0）
;   R3 = 常数 1

        LDI R1, 0        ; sum = 0
        LDI R2, 10       ; n = 10
        LDI R3, 1        ; 常数 1

loop:
        ADD R1, R1, R2   ; sum += n
        SUB R2, R2, R3   ; n--
        BNZ R2, loop     ; n != 0 继续

        OUT R1           ; 55
        HLT
