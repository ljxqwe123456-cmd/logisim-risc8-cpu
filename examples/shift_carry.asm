; 移位指令里的另两条（SLC / SRC，fn 12-13）的独立判据：OUT = 0x7E。
; 验证时机：§8 第 8 步（SLC / SRC 读 C 也写 C，要先有 C 寄存器；ALU 里的移位器与
;           fn 12-13 的译码、CWrite 多出来的那一项在第 2、4 步就该验过）。
;
; 这两条是"带进位"的那一半：固定移 1 位，C 就是移出去的那一位、也是补进来的那一位。
; 多字节移位靠它把两个寄存器串成一条链，链上两次的字节顺序相反：
;   右移：高字节先走，它的 bit0 要落进低字节的 bit7   16 位右移 0x35C2 >> 1 = 0x1AE1
;   左移：低字节先走，它的 bit7 要落进高字节的 bit0   16 位左移 0x2B96 << 1 = 0x572C
; 两组各自折成"高字节 + 低字节"再相加，所以顺序反了会丢掉那个跨字节的位，结果就变了。
;
; 判据怎么读，五个值各不相同：
;   0x7E = 正解。
;   0xFE = 右移那组的两条反了（低字节先走）。C 没能进低字节的 bit7，0x35C2 移出来是 0x1A61。
;   0x7D = 左移那组的两条反了（高字节先走）。C 没能进高字节的 bit0，0x2B96 移出来是 0x562C。
;   0xFD = C 整条不通。SLC / SRC 读不到 C 或写不进 C，症状一样：移进来的那一位恒为 0，
;          两组都退化成 0x1A61 与 0x562C。
;   0x4E = 两条的方向接反了（SLC 右移、SRC 左移）。跨字节的那一位还在 C 里走，但方向整体反了。
;
; 刻意不考 k=3、load-use 与 taken 作废（与 shift.asm 同一取舍）：
;   四个源寄存器都在 00-03 写、04 起才读，最近的一次是 k=4，走寄存器堆；
;   09 那条填充是为了把 0A 读 R7 从 k=3 推到 k=4；
;   06 读 R3 与 0B 读 R7 相隔 1 条（前递优先级 1），06 读 R2 与 0A 读 R4 相隔 2 条（优先级 2）——
;   那两条不通时也会算出别的值，不在上表里。
;   全文没有 LD、没有分支。
;
; 寄存器：R2:R3 = 右移那一组的 16 位值，R4:R5 = 左移那一组的，R6 = 填充用，R7 = 折叠和

        LDI R2, 0x35     ; 右移组高字节
        LDI R3, 0xC2     ; 右移组低字节   16 位值 = 0x35C2
        LDI R4, 0x2B     ; 左移组高字节
        LDI R5, 0x96     ; 左移组低字节   16 位值 = 0x2B96
        SRC R2, R2       ; 16 位右移一位：高字节先走，C ← 它的 bit0
        SRC R3, R3       ; 低字节跟上，C 从 bit0 进 bit7
        ADD R7, R2, R3   ; 折叠右移结果：0x1A + 0xE1 = 0xFB
        SLC R5, R5       ; 16 位左移一位：低字节先走，C ← 它的 bit7
        SLC R4, R4       ; 高字节跟上，C 从 bit7 进 bit0
        MOV R6, R6       ; 填充：把 10 读 R7 从 k=3 推到 k=4
        ADD R7, R7, R4   ; + 0x57 = 0x52
        ADD R7, R7, R5   ; + 0x2C = 0x7E
        OUT R7
        HLT
