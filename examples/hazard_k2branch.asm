; 冒险自测 3：分支的源相隔 2 条产生（k=2，不停顿，见 docs/datapath.md §5.1）
; 验证时机：§8 第 7 步（分支判零 + ID 前递网络）。
;           无 load-use、无停顿、无 k=3 —— 本条只考 ID 前递的 EX/MEM 那一路。
;
; 04 的 BZ 在 ID 段判零要的是 R3，而 R3 由 02 的 MOV 产生，两者相隔 2 条。
;   04 在 ID 的那一拍，02 正好走到 EX/MEM —— 所以分支操作数的 3 选 1 mux 必须接这一路。
;   此刻 MEM/WB 装的是 01（rd=2≠3），够不着；寄存器堆里 R3 也还是 0。
; 正解：不需要停顿，由 EX/MEM→ID 前递当场拿到 R3 = 5。
;
; 期望：OUT 显示 5（R3 = 5 ≠ 0 → 不跳，落到 06 的 OUT R3）。
; 若显示 0x10：分支操作数的 mux 只接了 MEM/WB、没接 EX/MEM，读到的 R3 是旧的 0 而误判"该跳"。
;
; 两条填充都不能省：
;   03 的 MOV R4,R2 把写 R3 的那条推到 i-2，让 BZ 走 k=2；它写 R4，
;     rd=4 不等于 BZ 的 [11:8]=3，所以不会触发停顿。
;   05 的 LDI R5,0 把 02 写的 R3 与 06 的 OUT 推到 k=4，避开 §4.1 的 k=3——
;     少了它，本条会连带依赖寄存器堆的下降沿写口，写口坏掉时输出 0x00，
;     而本条只声明了 5 / 0x10 两个值，搭建者会把这第三种结果误记到前递头上。

        LDI R1, 0x10
        LDI R2, 5
        MOV R3, R2       ; R3 = 5（写 Rd 的那条，i=2）
        MOV R4, R2       ; 填充①：把写 R3 的那条推到 i-2，让 BZ 走 k=2
        BZ  R3, wrong    ; R3 = 5 ≠ 0，应【不】跳（停在 EX/MEM→ID 前递这一路上）
        LDI R5, 0        ; 填充②：把 R3 与 OUT 的距离推到 k=4，避开 k=3
        OUT R3           ; 5    <- 正解走这里
        HLT
wrong:  OUT R1           ; 0x10 <- 误跳走这里
        HLT
