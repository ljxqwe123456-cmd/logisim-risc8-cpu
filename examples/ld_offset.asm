; 基址加偏移寻址（LD Rd,[Rs1+#off]，opcode 1100）的独立判据：OUT = 0x33。
; 验证时机：§8 第 4 步（译码器那一步就能跑；接上第 6 步的前递后复跑，0x00 那一行才判得动）。
; Hazard Unit 全文没有可触发的地方（见下）。
;
; 判据怎么读，三个值各不相同：
;   0x33 = 正解。
;   0x11 = 偏移没加上。两种接法都会退回"地址 = 基址"：ALUop 那三级 mux 的第三路没接
;          （落成 PASS.A，加法的偏移被丢掉），或 BSrc 的或门少了 op12 这一项
;          （off 上不了 ALU 的 B 口）。读到的都是 RAM[0x40] = 0x11。
;   0x00 = 前递没接。01 / 03 的 LDI 与紧跟的 STA 相隔 k=1（数据源在 A 口），两处都要前递；
;          这一级断了，寄存器堆当场读到的是两个寄存器的旧值 0，两格 RAM 都写成 0。
;          第 4 步是单周期、各级直连，每条指令独占一拍，这两对靠先后顺序天然成立，
;          所以那一行要到第 6 步接上前递之后才可能出错。
;
; 偏移取 4、两格取 0x11 / 0x33，就是为了让这两个症状分得开：丢掉偏移读到的是基址那一格。
; 两格分别用 R1 / R6 两个寄存器写，是为了不留下"某一格还够得着下降沿写口"的旁路——
; 一个寄存器连写两次再读，第二次读会落在 k=3 上，那条通路不经过前递，前递断了它也照样对。
; （square_lookup.asm 用 ADD 算出地址再 LD 间接，两条指令干的这件事；本条不需要那条 ADD。）
;
; 刻意不考 k=3、load-use 与 taken 作废（与 add16.asm / sub16.asm 同一取舍）：
;   05 的 LD 与 09 的 OUT 隔着三条填充，距离正好 k=4、走寄存器堆，所以不含 load-use；
;   全文没有一处间隔正好 3 条，也没有分支。出错时可以直接查译码器上为 op12 加的那几项
;   （BSrc 的或门输入、ALUop 的第三级 mux），不必先排除别的冒险。
;
; 寄存器：R1 / R6 = 要写进 RAM 的两个值，R2 = 基址 0x40，R3 = 读出的值，R7 = 填充用

        LDI R2, 0x40     ; 基址（到 05 的 LD 相隔 k=5，走寄存器堆）
        LDI R1, 0x11
        STA R1, 0x40     ; RAM[0x40] = 0x11（丢掉偏移时会读到这里）
        LDI R6, 0x33
        STA R6, 0x44     ; RAM[0x44] = 0x33
        LD  R3, [R2+#4]  ; R3 = RAM[0x40 + 4] = 0x33
        MOV R7, R7       ; 填充：把 R3 与 09 的 OUT 拉开到 k=4，避开 load-use
        MOV R7, R7
        MOV R7, R7
        OUT R3           ; 0x33
        HLT
