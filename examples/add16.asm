; 16 位加法（多字节，ADD/ADC）: 0x00FF + 0x0001 = 0x0100
; 验证时机：§8 第 8 步。**无 k=3、无 load-use、无分支**——四条 LDI 的排布刻意让每个
;           读 Rd 的那条的 RAW 距离落在 k=1 / k=2 / k>=4（见每条的标注），所以只需两个前递 mux
;           就能跑对，不依赖 §4.1 的下降沿写口。拿它验 C 标志时不会混进冒险问题。
; 把一个 16 位数拆成 高字节:低字节 两个 8 位寄存器：
;   A = 0x00FF → Ahi=R1(0x00), Alo=R2(0xFF)
;   B = 0x0001 → Bhi=R3(0x00), Blo=R4(0x01)
; 先 ADD 低字节（进位进 C），再 ADC 高字节（带上 C）。
; 结果: R6:R5 = 0x0100（OUT 依次显示低字节 0x00、高字节 0x01）

        LDI R1, 0x00     ; A 高字节
        LDI R3, 0x00     ; B 高字节   <- 排在这里（而非紧跟 R2）是为了把它推离 ADC 到 k=4
        LDI R2, 0xFF     ; A 低字节
        LDI R4, 0x01     ; B 低字节

        ADD R5, R2, R4   ; 低: 0xFF + 0x01 = 0x00, C=1（进位）  R2 距 02 k=2，R4 距 03 k=1
        ADC R6, R1, R3   ; 高: 0x00 + 0x00 + C = 0x01            R1 距 00 k=5，R3 距 01 k=4

        OUT R5           ; 低字节 0x00
        OUT R6           ; 高字节 0x01  → 结果 0x0100
        HLT
