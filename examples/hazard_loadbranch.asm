; 冒险自测 4：分支的源来自还在飞的 load（k=1 的 load→分支，见 docs/datapath.md §5.2 ③）
; 验证时机：§8 第 7 步（分支判零 + Hazard Unit 停顿条件的第三条）。
;           无 k=3 —— 本条只考"源还被关在在飞的 load 里"这一条。
;
; 05 的 BZ 在 ID 段判零要的是 R3，而 R3 由紧邻的 04 的 LD 产生（k=1）。
;   常规的分支停顿只停 1 拍——停完 04 才刚进 MEM，EX/MEM 里只有地址、没有数据，
;   而 ID_EX 已换成气泡（RegWrite=0），原来的停顿条件自动失效，BZ 就拿着旧 R3=0 判定"该跳"。
; 正解：本条要【停顿 2 拍】。判据是"源还被关在某个在飞的 load 里"——
;   §5.2 的 load_dep 第二个括号：ID_EX 或 EX/MEM 里还有一条写同一个 Rd 的 load。
;
; 期望：OUT 显示 0x05（R3 = 5 ≠ 0 → 不跳，落到 06 的 OUT R3）。
; 若显示 0x20：load→分支只停了 1 拍，BZ 读到旧的 R3 = 0 而误判跳转，跑进了 bad 分支。
;
; 02 的填充不能省：它把 00 的 LDI R1 与 04 的 LD 推到 k=4，避开 §4.1 的 k=3——
;   少了它，两者正好相隔 k=3，本条会连带依赖寄存器堆的下降沿写口；
;   写口坏掉时 LD 读到的 R1 是旧值 0，转而去读 RAM[0]（初值 0）、载入 R3=0，
;   BZ 判"该跳"走进 bad，同样显示 0x20，与"只停 1 拍"的症状一字不差。

        LDI R1, 0x20     ; 基址（写 Rd 的那条，i=0）
        LDI R2, 5
        LDI R4, 0        ; 填充：把 R1 与 LD 的距离推到 k=4，避开 k=3
        STA R2, 0x20     ; RAM[0x20] = 5
        LD  R3, [R1]     ; R3 = 5（写 R3 的那条是 load）
        BZ  R3, bad      ; R3 = 5 ≠ 0，应【不】跳（k=1 的 load→分支 → 要停 2 拍）
        OUT R3           ; 0x05 <- 正解走这里
        HLT
bad:    OUT R1           ; 0x20 <- 误跳走这里
        HLT
