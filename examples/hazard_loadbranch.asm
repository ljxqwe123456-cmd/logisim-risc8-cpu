; 冒险自测 4：分支的操作数来自还在飞的 load（k=1 的 load→分支，见 docs/datapath.md §5.2）
; 验证时机：§8 第 7 步（分支判定 + Hazard Unit 停顿条件）。
;           无 k=3、无 taken 分支。主力是"源还被关在在飞的 load 里"这一格停顿；
;           03 的 STA 另挂着一处 k=2 的 RAW，接漏前递优先级 2 会显示同一个 0x20。
;
; 05 的 BZ 在 EX 段判零要的是 R3，而 R3 由紧邻的 04 的 LD 产生（k=1）。
;   这时候照常放它走：05 到 EX 那一拍 04 才刚进 EX/MEM，而 load 的 ALUResult 是【地址】、
;   不是数据。优先级 1 被 !EX/MEM.MemToReg 挡掉、MEM/WB 里是 03 的 STA（RegWrite=0）也命中
;   不了，A 前递 mux 落到寄存器堆的旧值 R3=0，BZ 判"该跳"，跑进 bad 显示 0x20。
; 正解：本条要【停顿 1 拍】。判据是 04 还在 ID/EX 里（ID_EX.MemRead=1）且它的 rd 命中
;   05 的源槽 —— 停完 04 走进 MEM/WB，05 再从优先级 2 拿到数据。
; 本条能抓到"没停"，靠的正是上面那个 !EX/MEM.MemToReg（docs/datapath.md §4）：省掉它，
;   BZ 会从优先级 1 拿到地址 0x20（≠0）而不跳，顺落到 06 的 OUT R3，那时 R3 已写回 5，
;   显示 0x05 与正解一字不差，本条就成了假通过。
;
; 期望：OUT 显示 0x05（R3 = 5 ≠ 0 → 不跳，落到 06 的 OUT R3）。
; 若显示 0x20：两种成因，都要查——
;   ① 这条 load→分支没停，BZ 把地址当成了值而误判跳转，跑进了 bad 分支；
;   ② A 前递 mux 少了优先级 2：03 的 STA 读的 R2 距 01 是 k=2，取到旧值 0，
;      RAM[0x20] 没写进 5，04 的 LD 读回 0，05 的 BZ 一样判"该跳"。
;
; 02 的填充不能省：它把 00 的 LDI R1 与 04 的 LD 推到 k=4，避开 §4.1 的 k=3——
;   少了它，两者正好相隔 k=3，本条会连带依赖寄存器堆的下降沿写口；
;   写口坏掉时 LD 读到的 R1 是旧值 0，转而去读 RAM[0]（初值 0）、载入 R3=0，
;   BZ 判"该跳"走进 bad，同样显示 0x20，与"没停"的症状一字不差。

        LDI R1, 0x20     ; 基址（写 Rd 的那条，i=0）
        LDI R2, 5
        LDI R4, 0        ; 填充：把 R1 与 LD 的距离推到 k=4，避开 k=3
        STA R2, 0x20     ; RAM[0x20] = 5
        LD  R3, [R1]     ; R3 = 5（写 R3 的那条是 load）
        BZ  R3, bad      ; R3 = 5 ≠ 0，应【不】跳（k=1 的 load→分支 → 本拍要停 1 拍）
        OUT R3           ; 0x05 <- 正解走这里
        HLT
bad:    OUT R1           ; 0x20 <- 误跳走这里
        HLT
