; 间接跳转 JMP Rs（opcode 1101）的独立判据：OUT = 0x00。
; 验证时机：§8 第 7 步（跳转目标改从 A 前递 mux 取、PC 多一路来源，两件都在这一步接出来）。
;
; 判据怎么读，六个值各不相同：
;   0x00 = 正解。05 跳到 tgt，06 与 07 被作废，R3 始终是 02 写的 0。
;   0x11 = ID/EX 的 D 端清零漏了 ID_EX.JumpReg：06 是 05 后面第一条，本拍正在 ID，
;          它执行了、把 0x11 写进 R3。07 由 IF/ID 灌 0 正常作废。
;   0x22 = IF/ID 的 flush mux 漏了 ID_EX.JumpReg：07 是 05 后面第二条，本拍刚取进来，
;          它执行了、把 0x22 写进 R3。06 由 ID/EX 清零正常作废。
;          （两处都漏时 06 与 07 都执行，后写的那条覆盖先写的，看到的仍是 0x22。）
;   0x33 = 根本没跳（ID_EX.JumpReg 没锁存，或没接到 §2.6 目标 mux 的选择端）：
;          06、07、08 依次执行，R3 停在 08 写的 0x33，09 把这个值显示出来。
;          这一格同时兜住"两处 flush 都漏而 PC 也没动"的接法。
;   0x44 = 跳了，但目标值不是寄存器里的值（目标 mux 里接 A 前递 mux 输出的那一侧没接，
;          选到它时输出 0）：PC 回 0，程序从头再跑一遍，跑到 05 又回 0，显示屏停在 00 的 OUT R7 上。
;   0x55 = A 前递 mux 的优先级 1 没接：04 是 03 后面第二条 LDI，两次都写 R1，
;          05 读到的是 03 写的 bad（此刻在 MEM/WB），跳到 0B。
;
; 04 与 05 相隔 k=1，就是为了把"目标值必须经 A 前递 mux 送过来"这件事也钉住——
; 静态写两条 LDI 给同一个寄存器，前递断掉时读到的正好是那条不同的地址。
;
; 刻意不考 k=3、load-use 与 §4 前递优先级 2：
;   02 的 R3 与 0E 的 OUT 相隔 k=4、走寄存器堆；全文没有 load，也没有间隔正好 3 条。
;   03 与 05 那一对虽然是 k=2，但 04 的优先级 1 命中在先，优先级 2 接没接都一样。
;   出错时可以直接查译码器上为 op13 接出去的那几处（JumpReg 位、目标 mux、两处 flush 选择端）。
;
; 寄存器：R1 = 跳转目标，R3 = 判据寄存器，R7 = 跳转前的哨兵值

        LDI R7, 0x44     ; 哨兵：目标数据通路断掉时程序原地打转，显示屏停在这个值上
        OUT R7
        LDI R3, 0        ; 判据寄存器
        LDI R1, bad      ; R1 的旧值（前递优先级 1 断掉时 05 读到的就是它）
        LDI R1, tgt      ; 与 05 相隔 k=1：目标值必须经 A 前递 mux 的优先级 1 送来
        JMP R1           ; 应跳到 tgt，作废 06 与 07
        LDI R3, 0x11     ; 白取探针①（ID/EX 漏清才执行）
        LDI R3, 0x22     ; 白取探针②（IF/ID 漏清才执行）
        LDI R3, 0x33     ; 只有"根本没跳"才走得到
        OUT R3           ; 0x33
        HLT
bad:    LDI R3, 0x55     ; 前递优先级 1 断掉时跳到这里
        OUT R3           ; 0x55
        HLT
tgt:    OUT R3           ; 正解：R3 还是 0
        HLT
